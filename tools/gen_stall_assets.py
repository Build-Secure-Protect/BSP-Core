#!/usr/bin/env python3
"""Wraps the designed Market Stall models into the mod.

  python3 tools/gen_stall_assets.py            # copy and validate tools/stall/, write what wraps it
  python3 tools/gen_stall_assets.py --design   # rerun tools/gen_stall_design.py first

tools/stall/ is the design conversation's deliverable, written by tools/gen_stall_design.py (never
hand-edited). This script validates it again, copies the sixteen market_stall and sixteen stall_display models
into assets/bsp_core/models/block/ and the textures (PNGs and .mcmeta) into textures/block/stall/,
then writes the stall blockstate (facing x skin x broken x half), the empty upper-half model, the
display blockstate (facing x skin x broken), both item models (the vanilla skins) and the StallSkin
enum with the overlay points from layout.json and display_layout.json.
"""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from gen_material_assets import ASSETS  # noqa: E402
import gen_stall_design as design  # noqa: E402

STALL = ROOT / "tools/stall"
SKINS = ["fantasy", "scifi", "steampunk", "vanilla", "nether", "yatai", "nautical", "arcane"]
# skins whose models glow (lit strips, firebox, magma, lanterns, runes): the lower half gives light while whole
LIT = {"scifi", "steampunk", "nether", "yatai", "nautical", "arcane"}
JAVA = ROOT / "src/main/java/com/mrgregles/bsp_core/shop/StallSkin.java"


def display_blockstate():
    variants = {}
    for broken in ("false", "true"):
        for facing, y in (("north", 0), ("east", 90), ("south", 180), ("west", 270)):
            for skin in SKINS:
                v = {"model": f"bsp_core:block/stall_display_{skin}" + ("_broken" if broken == "true" else "")}
                if y:
                    v["y"] = y
                variants[f"broken={broken},facing={facing},skin={skin}"] = v
    return {"variants": variants}


def blockstate():
    variants = {}
    for broken in ("false", "true"):
        for facing, y in (("north", 0), ("east", 90), ("south", 180), ("west", 270)):
            for half in ("lower", "upper"):
                for skin in SKINS:
                    if half == "upper":
                        v = {"model": "bsp_core:block/market_stall_upper"}
                    else:
                        v = {"model": f"bsp_core:block/market_stall_{skin}" + ("_broken" if broken == "true" else "")}
                        if y:
                            v["y"] = y
                    variants[f"broken={broken},facing={facing},half={half},skin={skin}"] = v
    return {"variants": variants}


def java_float(v):
    return f"{float(v):g}f"


def java_enum(layout, dlayout):
    lines = ["package com.mrgregles.bsp_core.shop;", "",
             "/**", " * The Market Stall skins, in the designer's order, with the overlay points of each model in model units",
             " * (1/16 block, front facing north): the stock lamp and open lamp faces as x0, y0, x1, y1, z; the display",
             " * item's centre and its width in blocks; then the matching Stall Display's item centre and its GROUND-context scale.", " *", " * GENERATED by tools/gen_stall_assets.py from tools/stall/layout.json. Do not edit.", " */",
             "public enum StallSkin implements net.minecraft.util.StringRepresentable {"]
    for i, skin in enumerate(SKINS):
        l = layout[skin]
        sl, ol = l["stock_lamp"], l["open_lamp"]
        stock = ", ".join(java_float(v) for v in (sl[0][0], sl[0][1], sl[1][0], sl[1][1], sl[0][2]))
        open_ = ", ".join(java_float(v) for v in (ol[0][0], ol[0][1], ol[1][0], ol[1][1], ol[0][2]))
        item = ", ".join(java_float(v) for v in l["item"])
        lit = "true" if skin in LIT else "false"
        d = dlayout[skin]
        ditem = ", ".join(java_float(v) for v in d["item"])
        end = ";" if i == len(SKINS) - 1 else ","
        lines.append(f'    {skin.upper()}("{skin}", new float[]{{{stock}}}, new float[]{{{open_}}}, new float[]{{{item}}}, {java_float(l["item_scale"])}, {lit}, '
                     f'new float[]{{{ditem}}}, {java_float(d["ground_scale"])}){end}')
    lines += ["",
              "    public final String id;",
              "    /** x0, y0, x1, y1, z of the lamp face, model units. */",
              "    public final float[] stockLamp, openLamp;",
              "    /** The display item's centre, model units. */",
              "    public final float[] item;",
              "    /** The display item's width in blocks. */",
              "    public final float itemScale;",
              "    /** Whether the whole model glows (the lower half then gives light). */",
              "    public final boolean lit;",
              "    /** The Stall Display of this skin: its floating item's centre (model units) and the GROUND-context scale that fits it. */",
              "    public final float[] displayItem;",
              "    public final float displayScale;",
              "",
              "    StallSkin(String id, float[] stockLamp, float[] openLamp, float[] item, float itemScale, boolean lit, float[] displayItem, float displayScale) {",
              "        this.id = id;", "        this.stockLamp = stockLamp;", "        this.openLamp = openLamp;", "        this.item = item;",
              "        this.itemScale = itemScale;", "        this.lit = lit;", "        this.displayItem = displayItem;", "        this.displayScale = displayScale;", "    }", "",
              "    public StallSkin next() {", "        return values()[(ordinal() + 1) % values().length];", "    }", "",
              "    public static StallSkin byId(String id) {",
              "        for (StallSkin s : values()) {", "            if (s.id.equals(id)) {", "                return s;", "            }", "        }",
              "        return VANILLA;", "    }", "",
              "    @Override", "    public String getSerializedName() {", "        return id;", "    }", "}", ""]
    return "\n".join(lines)


def main():
    if "--design" in sys.argv:
        design.main()
    models = {p.stem: json.loads(p.read_text()) for p in sorted((STALL / "models").glob("*.json"))}
    for fn in (design.fantasy_textures, design.scifi_textures, design.scifi_textures_rest, design.steampunk_textures, design.vanilla_textures,
               design.nether_textures, design.yatai_textures, design.nautical_textures, design.arcane_textures):
        fn()  # the validator checks texture references against the design's own table
    design.validate(models)
    textures = {p.name for p in (STALL / "textures").iterdir()}
    layout = json.loads((STALL / "layout.json").read_text())
    dlayout = json.loads((STALL / "display_layout.json").read_text())
    assert list(layout) == SKINS and list(dlayout) == SKINS, f"layout skins {list(layout)} / {list(dlayout)}"
    for skin in SKINS:
        assert f"market_stall_{skin}" in models and f"market_stall_{skin}_broken" in models, skin
        assert f"stall_display_{skin}" in models and f"stall_display_{skin}_broken" in models, skin
    for name, mj in models.items():
        for ref in mj["textures"].values():
            assert ref.startswith("bsp_core:block/stall/"), f"{name}: texture {ref}"
            assert ref.split("/")[-1] + ".png" in textures, f"{name}: missing texture {ref}"
    tex_out = ASSETS / "textures/block/stall"
    if tex_out.exists():
        shutil.rmtree(tex_out)
    tex_out.mkdir(parents=True)
    for p in sorted((STALL / "textures").iterdir()):
        shutil.copyfile(p, tex_out / p.name)
    model_out = ASSETS / "models/block"
    for pattern in ("market_stall_*.json", "stall_display_*.json"):
        for old in model_out.glob(pattern):
            old.unlink()
    copied = 0
    for name, mj in models.items():
        (model_out / f"{name}.json").write_text(json.dumps(mj, indent=1) + "\n")
        copied += 1
    (model_out / "market_stall_upper.json").write_text(json.dumps(
        {"parent": "minecraft:block/block", "textures": {"particle": "bsp_core:block/stall/stall_vanilla_planks"}, "elements": []}, indent=1) + "\n")
    (ASSETS / "models/item/market_stall.json").write_text(json.dumps({"parent": "bsp_core:block/market_stall_vanilla"}, indent=1) + "\n")
    (ASSETS / "blockstates/market_stall.json").write_text(json.dumps(blockstate(), indent=1) + "\n")
    (ASSETS / "models/item/stall_display.json").write_text(json.dumps({"parent": "bsp_core:block/stall_display_vanilla"}, indent=1) + "\n")
    (ASSETS / "blockstates/stall_display.json").write_text(json.dumps(display_blockstate(), indent=1) + "\n")
    JAVA.write_text(java_enum(layout, dlayout))
    print(f"stall assets written: {copied} models, {len(textures)} texture files, {len(blockstate()['variants'])} + {len(display_blockstate()['variants'])} blockstate variants, StallSkin.java")


if __name__ == "__main__":
    main()
